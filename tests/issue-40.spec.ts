import { test, expect } from '@playwright/test';

test.beforeEach(async ({ page }) => {
 await page.addInitScript(() => localStorage.setItem('aero-formula.language', 'zh'));
 await page.route(/https:\/\/fonts\.(googleapis|gstatic)\.com\//, route => route.abort());
 await page.goto('/', { waitUntil: 'domcontentloaded' });
 await page.getByRole('combobox', { name: '画质', exact: true }).selectOption('Low');
});

test('test space configures the balloon platform before launch and keeps results free of recordings and charts', async ({ page }, info) => {
 const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
 const modes = page.locator('.mode-buttons button');
 await expect(modes).toHaveCount(3);
 const labs = page.locator('.lab-mode-buttons button'); await expect(labs).toHaveCount(2);
 expect((await labs.first().boundingBox())!.y).toBeGreaterThan((await modes.last().boundingBox())!.y);
 await page.getByRole('button', { name: /^测试空间/ }).click();
 await expect(page.getByRole('heading', { name: '飞机工坊', exact: true })).toBeVisible();
 await page.getByRole('button', { name: '重置设计', exact: true }).click();
 await page.getByRole('button', { name: /前往测试空间/ }).click();
 const height = page.getByLabel('平台高度数值', { exact: true });
 await height.fill('1200');
 await expect.poll(() => page.evaluate(() => (window as any).glider.scene.laboratory.platformHeight)).toBe(1200);
 const lab = await page.evaluate(() => (window as any).glider.scene.laboratory);
 expect(lab.balloons).toBe(4);
 await expect.poll(() => page.evaluate(() => (window as any).glider.telemetry.altitude)).toBeGreaterThan(1200);
 await page.getByLabel('启用弹射', { exact: true }).uncheck();
 await expect(page.getByLabel('弹射末端速度数值', { exact: true })).toBeDisabled();
 const throttle = page.getByLabel('油门', { exact: true });
 await throttle.press('Home');
 await page.screenshot({ path: info.outputPath('test-space-platform.png') });
 await page.getByRole('button', { name: '开始试飞', exact: true }).click();
 await expect(height).toBeDisabled();
 await expect.poll(() => page.evaluate(() => (window as any).glider.time)).toBeGreaterThan(0.25);
 expect(await page.evaluate(() => (window as any).glider.telemetry.speed)).toBe(0);
 expect(await page.evaluate(() => (window as any).glider.laboratory)).toMatchObject({ recordingBytes: 0, curveSamples: 0 });
 await page.getByRole('button', { name: '停止测试', exact: true }).click();
 const result = page.getByRole('region', { name: '测试结果', exact: true });
 await expect(result).toBeVisible(); await expect(result).toContainText('总飞行距离'); await expect(result).toContainText('最大G值');
 await expect(page.getByRole('button', { name: '导出回放', exact: true })).toHaveCount(0);
 await expect(page.locator('.result-instruments')).toHaveCount(0);
 expect(await page.evaluate(() => Object.keys(localStorage).filter(key => key.includes('.best.') && (key.includes('test-space') || key.includes('wind-tunnel'))))).toEqual([]);
 await page.getByRole('button', { name: '再试一次', exact: true }).click();
 await expect(height).toBeEnabled(); await expect(height).toHaveValue('1200');
 await page.getByLabel('启用弹射', { exact: true }).check();
 await page.getByLabel('弹射末端速度数值', { exact: true }).fill('30');
 await page.getByRole('button', { name: '开始试飞', exact: true }).click();
 await expect.poll(() => page.evaluate(() => (window as any).glider.telemetry.speed), { timeout: 60000 }).toBeGreaterThan(29);
 await expect(page.locator('.flight-status')).toContainText('飞行中', { timeout: 60000 });
 await page.getByRole('button', { name: '停止测试', exact: true }).click();
 await expect(result.locator('div').filter({ has: page.locator('dt', { hasText: /^起飞速度$/ }) }).last()).toContainText('30.0 m/s');
 await page.screenshot({ path: info.outputPath('test-space-results.png') });
 expect(errors).toEqual([]);
});

test('wind tunnel opens aero and structure data, smooths live inputs, survives breakup and stops manually', async ({ page }, info) => {
 const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
 await page.getByRole('button', { name: /^风洞/ }).click();
 await page.getByRole('button', { name: '重置设计', exact: true }).click();
 await page.getByRole('button', { name: /前往风洞/ }).click();
 await expect(page.getByRole('switch', { name: '气动图层', exact: true })).toHaveAttribute('aria-checked', 'true');
 await expect(page.getByRole('complementary', { name: '实时气动数据', exact: true })).toBeVisible();
 await expect(page.locator('.advanced-hud')).toHaveAttribute('open', '');
 const room = await page.evaluate(() => (window as any).glider.scene.laboratory);
 expect(room.walls).toHaveLength(6); expect(room.walls.every((wall: any) => wall.gridMeters === 1 && wall.tickMeters === 0.1)).toBe(true);
 await page.screenshot({ path: info.outputPath('wind-tunnel-room.png') });
 await page.getByLabel('气流速度数值', { exact: true }).fill('200');
 await page.getByLabel('滚转角度数值', { exact: true }).fill('30');
 await page.getByLabel('俯仰角度数值', { exact: true }).fill('8');
 await page.getByLabel('副翼控制比例数值', { exact: true }).fill('40');
 await page.getByLabel('升降舵控制比例数值', { exact: true }).fill('30');
 await page.getByLabel('方向舵控制比例数值', { exact: true }).fill('-25');
 expect(await page.evaluate(() => (window as any).glider.laboratory.wind)).toMatchObject({ speed: 20, roll: 0, pitch: 0, aileron: 0, elevator: 0, rudder: 0 });
 await page.getByRole('button', { name: '开始测试', exact: true }).click();
 await expect.poll(() => page.evaluate(() => (window as any).glider.laboratory.wind.speed)).toBeGreaterThan(20);
 await page.getByRole('button', { name: '暂停测试', exact: true }).click();
 const before = await page.evaluate(() => ({ time: (window as any).glider.time, wind: (window as any).glider.laboratory.wind }));
 await page.getByLabel('滚转角度数值', { exact: true }).fill('-30');
 expect(await page.evaluate(() => ({ time: (window as any).glider.time, wind: (window as any).glider.laboratory.wind }))).toEqual(before);
 await page.getByRole('button', { name: '继续测试', exact: true }).click();
 await expect.poll(() => page.evaluate(() => (window as any).glider.laboratory.wind.roll)).toBeLessThan(before.wind.roll);
 await expect.poll(() => page.evaluate(() => (window as any).glider.laboratory.fractures), { timeout: 90000 }).toBeGreaterThan(0);
 await expect.poll(() => page.evaluate(() => (window as any).glider.laboratory.wind.speed), { timeout: 90000 }).toBe(200);
 expect(await page.evaluate(() => (window as any).glider.state)).toBe('flight');
 expect(await page.evaluate(() => (window as any).glider.result)).toBeNull();
 expect(await page.evaluate(() => (window as any).glider.laboratory)).toMatchObject({ recordingBytes: 0, curveSamples: 0 });
 await page.getByRole('button', { name: '停止测试', exact: true }).click();
 await expect(page.getByRole('heading', { name: '风洞测试结束', exact: true })).toBeVisible();
 expect(await page.evaluate(() => (window as any).glider.result.landing)).toBe('manual');
 await page.getByRole('button', { name: '返回设计改进', exact: true }).click();
 await expect(page.getByRole('heading', { name: '飞机工坊', exact: true })).toBeVisible();
 expect(errors).toEqual([]);
});
